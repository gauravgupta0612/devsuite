import * as fs from 'fs';
import * as path from 'path';
import { Evidence, RepoIndex } from './types';
import { languageLabel } from './languages';

export interface GuideOptions {
  /** Prefix that makes repo-relative paths valid from where the guide is saved, e.g. "../" for .repopilot/ONBOARDING.md */
  linkPrefix?: string;
}

const enc = (p: string) => p.split('/').map(encodeURIComponent).join('/');

export function evidenceLink(e: Evidence, prefix = ''): string {
  const label = e.line ? `${e.file}:${e.line}` : e.file;
  return `[${label}](${prefix}${enc(e.file)}${e.line ? `#L${e.line}` : ''})`;
}

function fmt(n: number): string {
  return n.toLocaleString('en-US');
}

/** Generate a project-specific onboarding guide in Markdown. Every claim links to the source that backs it. */
export function generateOnboardingGuide(index: RepoIndex, opts: GuideOptions = {}): string {
  const p = opts.linkPrefix ?? '';
  const link = (e: Evidence) => evidenceLink(e, p);
  const fileLink = (f: string, line?: number) => link({ file: f, line });
  const out: string[] = [];
  const totalLines = index.files.reduce((s, f) => s + f.lines, 0);
  const codeLangs = index.languages.filter(l => !['other', 'json', 'markdown', 'yaml', 'xml', 'html', 'css'].includes(l.language));

  out.push(`# ${index.name} — Onboarding Guide`);
  out.push('');
  out.push(`> Generated by **RepoPilot** on ${new Date(index.scannedAt).toLocaleString()} from ${fmt(index.files.length)} files ` +
    `(${fmt(totalLines)} lines) in ${(index.durationMs / 1000).toFixed(1)}s. Every statement links to the evidence it was derived from.` +
    (index.truncated ? ' **Scan was truncated** — raise `repopilot.maxFiles` for full coverage.' : ''));
  out.push('');

  // ---- Summary
  out.push('## At a glance');
  out.push('');
  const primary = codeLangs.slice(0, 3).map(l => languageLabel(l.language)).join(', ') || 'n/a';
  out.push(`- **Primary languages:** ${primary}`);
  if (index.frameworks.length) out.push(`- **Frameworks & libraries:** ${index.frameworks.slice(0, 8).map(f => f.name).join(', ')}`);
  if (index.buildSystems.length) out.push(`- **Build / tooling:** ${index.buildSystems.map(b => b.name).join(', ')}`);
  out.push(`- **Entry points found:** ${index.entryPoints.length}`);
  out.push(`- **Internal dependencies:** ${fmt(index.edges.length)} links between files, ${index.cycles.length} circular group(s)`);
  out.push(`- **Tests:** ${index.testFiles ? `${fmt(index.testFiles)} test files` : 'no test files detected'}`);
  if (index.readme) out.push(`- **README:** ${fileLink(index.readme)}`);
  out.push('');

  if (index.readme) {
    try {
      const text = fs.readFileSync(path.join(index.root, index.readme), 'utf8');
      const para = text.split(/\r?\n\s*\r?\n/).map(s => s.trim()).find(s => s && !s.startsWith('#') && !s.startsWith('[!') && !s.startsWith('<') && !s.startsWith('!['));
      if (para) {
        out.push('**What the README says:**');
        out.push('');
        out.push(para.split(/\r?\n/).map(l => `> ${l}`).join('\n').slice(0, 800));
        out.push('');
      }
    } catch { /* ignore */ }
  }

  // ---- Languages
  out.push('## Languages');
  out.push('');
  out.push('| Language | Files | Lines |');
  out.push('|---|---:|---:|');
  for (const l of index.languages.slice(0, 12)) out.push(`| ${languageLabel(l.language)} | ${fmt(l.files)} | ${fmt(l.lines)} |`);
  out.push('');

  // ---- Frameworks
  if (index.frameworks.length) {
    out.push('## Frameworks & platforms');
    out.push('');
    for (const f of index.frameworks) out.push(`- **${f.name}** — ${f.evidence.slice(0, 2).map(link).join(', ')}`);
    out.push('');
  }

  // ---- Build
  out.push('## How to build, run and test');
  out.push('');
  if (index.buildSystems.length) {
    out.push(`Build systems: ${index.buildSystems.map(b => `**${b.name}** (${link(b.evidence[0])})`).join(', ')}.`);
    out.push('');
  }
  if (index.buildCommands.length) {
    out.push('| Command | Where | Source |');
    out.push('|---|---|---|');
    for (const c of index.buildCommands.slice(0, 30)) {
      out.push(`| \`${c.command}\` | \`${c.cwd || '.'}\` | ${link(c.evidence)}${c.evidence.note ? ` → \`${c.evidence.note.replace(/\|/g, '\\|').slice(0, 60)}\`` : ''} |`);
    }
  } else {
    out.push('_No build commands were declared in manifests. Check the README or CI configuration._');
  }
  out.push('');

  // ---- Entry points
  out.push('## Entry points — start reading here');
  out.push('');
  if (index.entryPoints.length) {
    for (const e of index.entryPoints.slice(0, 25)) {
      out.push(`- ${fileLink(e.file, e.evidence.file === e.file ? e.evidence.line : undefined)} — ${e.reason}${e.evidence.file !== e.file ? ` (declared in ${link(e.evidence)})` : ''}`);
    }
  } else out.push('_No obvious entry point was detected._');
  out.push('');

  // ---- Architecture
  out.push('## Architecture — modules');
  out.push('');
  out.push('| Module | Files | Lines | Languages | Depends on |');
  out.push('|---|---:|---:|---|---|');
  for (const m of index.modules.slice(0, 25)) {
    out.push(`| \`${m.name}\` | ${fmt(m.files)} | ${fmt(m.lines)} | ${m.languages.map(l => languageLabel(l as any)).join(', ')} | ${m.dependsOn.slice(0, 5).map(d => `\`${d}\``).join(', ') || '—'} |`);
  }
  out.push('');
  const mermaid = moduleMermaid(index);
  if (mermaid) {
    out.push('```mermaid');
    out.push(mermaid);
    out.push('```');
    out.push('');
  }

  // ---- Hotspots
  if (index.hotspots.length) {
    out.push('## Core files (most depended upon)');
    out.push('');
    out.push('Changes here have the widest blast radius — read them early and change them carefully.');
    out.push('');
    for (const h of index.hotspots.slice(0, 12)) out.push(`- ${fileLink(h.file)} — used by **${h.dependents}** files`);
    out.push('');
  }

  // ---- Cycles
  if (index.cycles.length) {
    out.push('## Circular dependencies');
    out.push('');
    for (const c of index.cycles.slice(0, 8)) out.push(`- ${c.slice(0, 6).map(f => fileLink(f)).join(' ↔ ')}${c.length > 6 ? ` … (+${c.length - 6})` : ''}`);
    out.push('');
  }

  // ---- External deps
  const prod = index.externalDependencies.filter(d => !d.dev);
  if (prod.length) {
    out.push('## Key external dependencies');
    out.push('');
    for (const d of prod.slice(0, 20)) out.push(`- \`${d.name}\`${d.version ? ` ${d.version}` : ''} (${d.ecosystem}) — ${link(d.evidence)}`);
    if (prod.length > 20) out.push(`- … and ${prod.length - 20} more`);
    out.push('');
  }

  // ---- Unresolved
  if (index.unresolved.length) {
    out.push('## Unresolved internal references');
    out.push('');
    out.push('These look like references to project code that RepoPilot could not find in the workspace (missing members, generated files, or path aliases).');
    out.push('');
    for (const u of index.unresolved.slice(0, 15)) out.push(`- \`${u.specifier}\` in ${fileLink(u.from, u.line)}`);
    if (index.unresolved.length > 15) out.push(`- … and ${index.unresolved.length - 15} more`);
    out.push('');
  }

  out.push('## Suggested first day');
  out.push('');
  let step = 1;
  if (index.readme) out.push(`${step++}. Read ${fileLink(index.readme)}.`);
  if (index.buildCommands.length) out.push(`${step++}. Build it: \`${index.buildCommands.find(c => /install|build|package/.test(c.command))?.command ?? index.buildCommands[0].command}\`.`);
  if (index.entryPoints.length) out.push(`${step++}. Trace the flow from ${fileLink(index.entryPoints[0].file)}.`);
  if (index.hotspots.length) out.push(`${step++}. Study the core file ${fileLink(index.hotspots[0].file)} — ${index.hotspots[0].dependents} files rely on it.`);
  if (index.testFiles) out.push(`${step++}. Run the tests to confirm your environment works.`);
  out.push('');
  return out.join('\n');
}

export function moduleMermaid(index: RepoIndex, max = 15): string | undefined {
  const mods = index.modules.slice(0, max);
  const names = new Set(mods.map(m => m.name));
  const id = (n: string) => 'm_' + n.replace(/[^A-Za-z0-9]/g, '_');
  const lines = ['graph LR'];
  for (const m of mods) lines.push(`  ${id(m.name)}["${m.name.replace(/"/g, "'")} (${m.files})"]`);
  let edges = 0;
  for (const m of mods) for (const d of m.dependsOn) if (names.has(d)) { lines.push(`  ${id(m.name)} --> ${id(d)}`); edges++; }
  return edges || mods.length > 1 ? lines.join('\n') : undefined;
}
